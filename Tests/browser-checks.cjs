const { chromium } = require(process.env.SALAS_PLAYWRIGHT_PATH || require('path').join(require('os').tmpdir(), 'salas-browser-check/node_modules/playwright'));
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.env.SALAS_TEST_URL || 'http://localhost:5018');
    await page.locator('#demo-accounts').waitFor({ state: 'visible' });
    await page.screenshot({ path: path.join(os.tmpdir(), 'salas-login.png'), fullPage: true });
    async function login(profile) {
      await page.locator(`[data-demo="${profile}"]`).click();
      await page.locator('#login-submit').click();
      await page.locator('#app-shell').waitFor({ state: 'visible' });
      await page.locator('#booking-fields:not([disabled])').waitFor();
    }
    async function logout() {
      await page.locator('#logout').click();
      await page.locator('#login-screen').waitFor({ state: 'visible' });
    }
    await login('admin');
    assert.equal(await page.locator('#cadastros').isVisible(), true);
    const suffix = Date.now();
    let room = `Sala navegador ${suffix}`, turma = `Turma navegador ${suffix}`;
    await page.locator('#room-form [name="nome"]').fill(room);
    await page.locator('#room-form [name="localizacao"]').fill('Bloco de testes');
    await page.locator('#room-form button[type="submit"]').click();
    await page.locator('#room-message.success').waitFor({ state: 'visible' });
    await page.locator('#class-form [name="nome"]').fill(turma);
    await page.locator('#class-form [name="curso"]').fill('Desenvolvimento de Sistemas');
    await page.locator('#class-form button[type="submit"]').click();
    await page.locator('#class-message.success').waitFor({ state: 'visible' });
    await logout();
    await login('professor');
    assert.equal(await page.locator('#cadastros').isVisible(), false);
    assert.equal(await page.locator('.cancel-button').count(), 0);
    assert.equal(await page.locator('[data-edit-room], [data-edit-class]').count(), 0);
    await page.locator('#class').selectOption({ label: `${turma} · Manhã` });
    await page.locator('#room').selectOption({ label: `${room} · 30 lugares` });
    await page.locator('#activity').fill(`Aula navegador ${suffix}`);
    await page.locator('#booking-date').fill('2026-12-16');
    await page.locator('#submit').click();
    await page.locator('#form-message.success').waitFor({ state: 'visible' });
    assert.ok((await page.locator('#reservations').textContent()).includes(`Aula navegador ${suffix}`));
    await logout();
    await login('admin');
    const roomCard = page.locator('.room-card').filter({ has: page.getByRole('heading', { name: room, exact: true }) });
    await roomCard.getByRole('button').click();
    assert.equal(await page.locator('#room-form [name="nome"]').inputValue(), room);
    assert.equal(await page.locator('#room-form [name="capacidade"]').inputValue(), '30');
    await page.locator('#room-form [name="nome"]').fill('Alteração descartada');
    await page.locator('#room-form [data-cancel-edit]').click();
    assert.equal(await page.locator('#room-form [name="nome"]').inputValue(), '');
    assert.ok((await page.locator('#rooms-list').textContent()).includes(room));
    await roomCard.getByRole('button').click();
    room += ' editada';
    await page.locator('#room-form [name="nome"]').fill(room);
    await page.locator('#room-form [name="capacidade"]').fill('35');
    await page.locator('#room-form [name="localizacao"]').fill('Bloco atualizado');
    await page.locator('#room-form button[type="submit"]').click();
    await page.locator('#room-message.success').waitFor({ state: 'visible' });
    assert.ok((await page.locator('#room-message').textContent()).includes('atualizada'));
    assert.equal(await page.locator('#room-form [data-cancel-edit]').isVisible(), false);
    const classCard = page.locator('.room-card').filter({ has: page.getByRole('heading', { name: turma, exact: true }) });
    await classCard.getByRole('button').click();
    assert.equal(await page.locator('#class-form [name="nome"]').inputValue(), turma);
    turma += ' editada';
    await page.locator('#class-form [name="nome"]').fill(turma);
    await page.locator('#class-form [name="curso"]').fill('Curso atualizado');
    await page.locator('#class-form [name="turno"]').selectOption('Noite');
    await page.locator('#class-form [name="quantidadeAlunos"]').fill('28');
    await page.locator('#class-form button[type="submit"]').click();
    await page.locator('#class-message.success').waitFor({ state: 'visible' });
    assert.ok((await page.locator('#class-message').textContent()).includes('atualizada'));
    assert.ok((await page.locator('#room').textContent()).includes(`${room} · 35 lugares`));
    assert.ok((await page.locator('#class').textContent()).includes(`${turma} · Noite`));
    await page.locator('#agenda-date').fill('2026-12-16');
    await page.locator('#agenda-date').dispatchEvent('change');
    await page.locator('#search').fill(`Aula navegador ${suffix}`);
    assert.ok((await page.locator('#reservations').textContent()).includes(room));
    assert.ok((await page.locator('#reservations').textContent()).includes(turma));
    await page.locator('.cancel-button').click();
    await page.locator('#cancel-reason').fill('Reorganização do espaço pela coordenação');
    await page.locator('#cancel-confirm').click();
    await page.locator('#cancel-dialog').waitFor({ state: 'hidden' });
    await page.locator('#show-cancelled').check();
    await page.locator('.badge.cancelled').waitFor({ state: 'visible' });
    assert.ok((await page.locator('.cancel-reason').textContent()).includes('Reorganização'));
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(os.tmpdir(), 'salas-admin.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Sem rolagem horizontal no celular');
    await page.screenshot({ path: path.join(os.tmpdir(), 'salas-mobile.png'), fullPage: true });
    await page.reload();
    await page.locator('#app-shell').waitFor({ state: 'visible' });
    await page.locator('#booking-fields:not([disabled])').waitFor();
    assert.ok((await page.locator('#rooms-list').textContent()).includes(room));
    assert.ok((await page.locator('#classes-list').textContent()).includes(turma));
    assert.equal(await page.locator('.side-note, .side-footer').count(), 0);
    assert.equal((await page.locator('.account-links').innerText()).replace(/\s/g, ''), 'Conta|Sair');
    await page.locator('#account').click();
    await page.locator('#account-fields:not([disabled])').waitFor();
    assert.equal(await page.locator('#account-email').inputValue(), 'admin@senai.demo');
    await page.locator('#account-name').fill('Coordenação editada no navegador');
    await page.locator('#account-save').click();
    await page.locator('#account-dialog').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#user-name').textContent(), 'Coordenação editada no navegador');
    await logout();
    await login('professor');
    await page.locator('#account').click();
    await page.locator('#account-fields:not([disabled])').waitFor();
    assert.equal(await page.locator('#account-email').inputValue(), 'professor@senai.demo');
    await page.locator('#account-name').fill('Professor editado no navegador');
    await page.locator('#account-save').click();
    await page.locator('#account-dialog').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#user-name').textContent(), 'Professor editado no navegador');
    await page.reload();
    await page.locator('#booking-fields:not([disabled])').waitFor();
    assert.equal(await page.locator('#user-name').textContent(), 'Professor editado no navegador');
    assert.deepEqual(errors, []);
    console.log('OK: cadastros, reservas, permissões, layout móvel, Conta | Sair e edição de conta nos dois perfis.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
